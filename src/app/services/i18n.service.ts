export type TranslationKey = keyof (typeof translations)[typeof DEFAULT_LANGUAGE];

@Injectable({ providedIn: 'root' })
export class I18nService {
  readonly availableLanguages: AppLanguage[] = ['EN', 'SW'];
  readonly language = signal<AppLanguage>(this.getInitialLanguage());

  t(key: TranslationKey, params?: Record<string, string | number>): string {
    const value: string = translations[this.language()][key] ?? translations[DEFAULT_LANGUAGE][key] ?? key;
    if (!params) {
      return value;
    }

    let formatted: string = value;
    for (const [param, replacement] of Object.entries(params)) {
      formatted = formatted.replace(new RegExp(`\\{\\{\\s*${param}\\s*\\}\\}`, 'g'), String(replacement));
    }

    return formatted;
  }

  setLanguage(language: AppLanguage): void {
    this.language.set(language);
    localStorage.setItem('admin-language', language);
  }

  private getInitialLanguage(): AppLanguage {
    const stored = localStorage.getItem('admin-language');
    if (stored === 'EN' || stored === 'SW') {
      return stored;
    }
    return DEFAULT_LANGUAGE;
  }
}
